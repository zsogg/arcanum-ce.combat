// Tests for `game/area.c` - what a saved area list *means* after the list
// changes under it.
//
// `harness/area-count-check.sh` in `arcanum-work` already gates the other
// half of this: card H4 put a `magic + count` prefix in front of the Area
// block so a save survives an area being added or removed without dying at
// the next sentinel (MODDING-NOTES.md quirk 17). That is **stream** safety -
// the right number of bytes is read.
//
// This suite is about **identity**: after the read succeeds, does the
// discovery state still describe the same places? `area_mod_load` builds
// every array by an entry's *rank* in the key-sorted `mes/gamearea.mes`
// (mes.c sorts on load, so rank is id order), and `area_load` copies flags
// by position. Rank and id are the same number only while the ids are
// contiguous from zero, and even then a removal renumbers everything above
// it. Card H9 exists to measure exactly where that breaks, so several tests
// below assert a *wrong* mapping on purpose and say so: they are the
// regression instrument for a limitation, not a claim that it is fine.
//
// Observability without a game: `area_set_known` needs a real PC object and
// `player_get_local_pc_obj`, which no unit test has. It is not needed -
// `area_save` writes `area_flags` straight out, so a hand-built save loaded
// and then saved again reveals every flag and both last-known values.

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#ifndef _WIN32
#include <signal.h>
#include <sys/wait.h>
#include <unistd.h>
#endif

#include "game/area.h"

#include "tig/tig.h"

#include "test_harness.h"

#define AREA_DIR "./mes"
#define AREA_FIXTURE "./mes/gamearea.mes"
#define SAVE_FIXTURE "./arcanum_test_area.sav"

#define MAX_TEST_AREAS 16

// The layout `area_save` writes and `area_load` reads. Nine flag arrays and
// nine int32s: the shared set plus one per player slot.
typedef struct {
    int count;
    unsigned char flags[MAX_TEST_AREAS];
    int last;
    unsigned char player_flags[8][MAX_TEST_AREAS];
    int player_last[8];
} AreaBlock;

#define AREA_MAGIC 0x41455241u /* 'AREA' */
#define GAMELIB_SENTINEL 0xBEEFCAFEu

static bool area_fixture_loaded;

// -- fixtures --------------------------------------------------------------

// One `mes/gamearea.mes` line per id, in the shape the shipped file uses:
// `{id}{X, Y, xoff, yoff /NAME/description/Radius:N}`. Names are the handle
// on identity: a name that moved rank is a location whose discovery state
// moved with it.
static bool write_area_fixture(const int* ids, const char* const* names, int count)
{
    FILE* stream;
    int index;

    tig_file_mkdir(AREA_DIR);
    stream = fopen(AREA_FIXTURE, "wb");
    if (stream == NULL) {
        return false;
    }

    fprintf(stream, "// generated by test_area.c\n");
    for (index = 0; index < count; index++) {
        fprintf(stream,
            "{%d}{%d, %d, 0, 0 /%s/test area %d./Radius:5}\n",
            ids[index],
            1000 + 64 * ids[index],
            2000 + 64 * ids[index],
            names[index],
            ids[index]);
    }

    fclose(stream);
    return true;
}

// `write_area_fixture` with generated names, so a caller that only cares
// about counts does not have to build a name table.
static bool write_areas_named(const int* ids, int count)
{
    char storage[MAX_TEST_AREAS][16];
    const char* names[MAX_TEST_AREAS];
    int index;

    if (count > MAX_TEST_AREAS) {
        return false;
    }

    for (index = 0; index < count; index++) {
        snprintf(storage[index], sizeof(storage[index]), "AREA%02d", ids[index]);
        names[index] = storage[index];
    }

    return write_area_fixture(ids, names, count);
}

// Contiguous 0..count-1, the only shape the engine's storage model actually
// supports.
static bool write_contiguous_areas(int count)
{
    int ids[MAX_TEST_AREAS];
    int index;

    if (count > MAX_TEST_AREAS) {
        return false;
    }
    for (index = 0; index < count; index++) {
        ids[index] = index;
    }
    return write_areas_named(ids, count);
}

static bool reload_areas(void)
{
    if (area_fixture_loaded) {
        area_mod_unload();
        area_fixture_loaded = false;
    }
    if (!area_mod_load()) {
        return false;
    }
    area_fixture_loaded = true;
    return true;
}

// -- save blocks -----------------------------------------------------------

static void block_init(AreaBlock* block, int count)
{
    memset(block, 0, sizeof(*block));
    block->count = count;
}

// `with_magic` false writes the original's layout - no prefix - which is what
// every save written before card H4 looks like. `with_sentinel` appends
// gamelib's 0xBEEFCAFE, which is how `area_load` recovers the count from such
// a save.
static bool write_save_block(const AreaBlock* block, bool with_magic, bool with_sentinel)
{
    FILE* stream;
    unsigned int word;
    int player;

    stream = fopen(SAVE_FIXTURE, "wb");
    if (stream == NULL) {
        return false;
    }

    if (with_magic) {
        word = AREA_MAGIC;
        fwrite(&word, sizeof(word), 1, stream);
        fwrite(&(block->count), sizeof(block->count), 1, stream);
    }

    fwrite(block->flags, 1, (size_t)block->count, stream);
    fwrite(&(block->last), sizeof(block->last), 1, stream);

    for (player = 0; player < 8; player++) {
        fwrite(block->player_flags[player], 1, (size_t)block->count, stream);
        fwrite(&(block->player_last[player]), sizeof(block->player_last[player]), 1, stream);
    }

    if (with_sentinel) {
        word = GAMELIB_SENTINEL;
        fwrite(&word, sizeof(word), 1, stream);
    }

    fclose(stream);
    return true;
}

static bool load_save_block(void)
{
    GameLoadInfo load_info;
    TigFile* stream;
    bool ok;

    stream = tig_file_fopen(SAVE_FIXTURE, "rb");
    if (stream == NULL) {
        return false;
    }

    memset(&load_info, 0, sizeof(load_info));
    load_info.stream = stream;
    ok = area_load(&load_info);
    tig_file_fclose(stream);

    return ok;
}

// Save, then read the bytes back. This is the whole observation window: what
// `area_save` writes *is* `area_flags` and both last-known values.
static bool save_and_read_block(AreaBlock* block)
{
    TigFile* out;
    FILE* in;
    unsigned int magic = 0;
    int player;
    bool ok;

    out = tig_file_fopen(SAVE_FIXTURE, "wb");
    if (out == NULL) {
        return false;
    }
    ok = area_save(out);
    tig_file_fclose(out);
    if (!ok) {
        return false;
    }

    memset(block, 0, sizeof(*block));
    in = fopen(SAVE_FIXTURE, "rb");
    if (in == NULL) {
        return false;
    }
    if (fread(&magic, sizeof(magic), 1, in) != 1
        || magic != AREA_MAGIC
        || fread(&(block->count), sizeof(block->count), 1, in) != 1
        || block->count < 0
        || block->count > MAX_TEST_AREAS) {
        fclose(in);
        return false;
    }
    if (fread(block->flags, 1, (size_t)block->count, in) != (size_t)block->count
        || fread(&(block->last), sizeof(block->last), 1, in) != 1) {
        fclose(in);
        return false;
    }
    for (player = 0; player < 8; player++) {
        if (fread(block->player_flags[player], 1, (size_t)block->count, in) != (size_t)block->count
            || fread(&(block->player_last[player]), sizeof(block->player_last[player]), 1, in) != 1) {
            fclose(in);
            return false;
        }
    }
    fclose(in);
    return true;
}

// -- the tests -------------------------------------------------------------

TEST(round_trip_preserves_flags_and_last_known)
{
    AreaBlock written;
    AreaBlock read_back;

    CHECK(write_contiguous_areas(6));
    CHECK(reload_areas());
    CHECK_INT(area_count(), 6);

    block_init(&written, 6);
    written.flags[2] = 1;
    written.flags[5] = 1;
    written.last = 5;
    // The per-player arrays are a separate serialization path with the same
    // positional model, so every case here checks one of them too.
    written.player_flags[3][1] = 1;
    written.player_last[3] = 1;

    CHECK(write_save_block(&written, true, false));
    CHECK(load_save_block());
    CHECK(save_and_read_block(&read_back));

    CHECK_INT(read_back.count, 6);
    CHECK_INT(read_back.flags[2], 1);
    CHECK_INT(read_back.flags[5], 1);
    CHECK_INT(read_back.flags[0], 0);
    CHECK_INT(read_back.last, 5);
    CHECK_INT(read_back.player_flags[3][1], 1);
    CHECK_INT(read_back.player_last[3], 1);
}

// SUPPORTED transition: append at the end, every earlier area keeps its rank.
TEST(appending_an_area_keeps_every_earlier_area)
{
    AreaBlock written;
    AreaBlock read_back;

    CHECK(write_contiguous_areas(6));
    CHECK(reload_areas());

    block_init(&written, 6);
    written.flags[2] = 1;
    written.flags[5] = 1;
    written.last = 5;
    written.player_flags[0][5] = 1;
    CHECK(write_save_block(&written, true, false));

    // The mod installs: one more contiguous entry.
    CHECK(write_contiguous_areas(7));
    CHECK(reload_areas());
    CHECK_INT(area_count(), 7);

    CHECK(load_save_block());
    CHECK(save_and_read_block(&read_back));

    CHECK_INT(read_back.count, 7);
    CHECK_INT(read_back.flags[2], 1);
    CHECK_INT(read_back.flags[5], 1);
    CHECK_STR(area_get_name(5), "AREA05");
    // The new area is unknown, which is what an area the save never saw
    // should be - not whatever byte followed the block.
    CHECK_INT(read_back.flags[6], 0);
    CHECK_INT(read_back.player_flags[0][5], 1);
    CHECK_INT(read_back.player_flags[0][6], 0);
    CHECK_INT(read_back.last, 5);
}

// SUPPORTED for the areas that remain, with one caveat this pins: removing
// the *top* area leaves `area_last_known_area` pointing past the list.
TEST(removing_the_top_area_leaves_last_known_out_of_range)
{
    AreaBlock written;
    AreaBlock read_back;

    CHECK(write_contiguous_areas(7));
    CHECK(reload_areas());

    block_init(&written, 7);
    written.flags[2] = 1;
    written.flags[6] = 1;
    written.last = 6;
    CHECK(write_save_block(&written, true, false));

    CHECK(write_contiguous_areas(6));
    CHECK(reload_areas());
    CHECK_INT(area_count(), 6);

    CHECK(load_save_block());
    CHECK(save_and_read_block(&read_back));

    CHECK_INT(read_back.count, 6);
    CHECK_INT(read_back.flags[2], 1);
    // The removed area's flag is gone, and nothing below it moved.
    CHECK_INT(read_back.flags[5], 0);
    // LIMITATION: the last-known index is a raw ordinal with no range check
    // on load, so it now names an area that does not exist. `area_get_name`
    // is bounds-checked and answers NULL, which is why this is a stale
    // world-map destination rather than a read out of bounds.
    CHECK_INT(read_back.last, 6);
    CHECK(area_get_name(read_back.last) == NULL);
}

// LIMITATION: removing an area *below* another renumbers every rank above it,
// so the saved discovery state lands on the wrong place. This is the case
// mods/ID-BUDGETS.md says a contiguity rule cannot fix, measured.
TEST(removing_a_lower_area_moves_state_to_the_wrong_place)
{
    static const int after_ids[] = { 0, 1, 2, 3, 4, 5 };
    static const char* const after_names[] = {
        "AREA00", "AREA01", "AREA02", "AREA04", "AREA05", "AREA06"
    };
    AreaBlock written;
    AreaBlock read_back;

    CHECK(write_contiguous_areas(7));
    CHECK(reload_areas());
    CHECK_STR(area_get_name(5), "AREA05");

    // The player discovered AREA05, which is at rank 5.
    block_init(&written, 7);
    written.flags[5] = 1;
    written.last = 5;
    written.player_flags[1][5] = 1;
    CHECK(write_save_block(&written, true, false));

    // AREA03 is uninstalled. The remaining areas are renumbered to stay
    // contiguous - which is the *correct* authoring response to a removal,
    // and still moves everything above it down one rank.
    CHECK(write_area_fixture(after_ids, after_names, 6));
    CHECK(reload_areas());
    CHECK_INT(area_count(), 6);
    CHECK_STR(area_get_name(4), "AREA05");
    CHECK_STR(area_get_name(5), "AREA06");

    CHECK(load_save_block());
    CHECK(save_and_read_block(&read_back));

    // The flag stayed at rank 5, so the place the player actually discovered
    // is now unknown...
    CHECK_INT(read_back.flags[4], 0);
    // ...and a place they never visited is marked discovered.
    CHECK_INT(read_back.flags[5], 1);
    CHECK_STR(area_get_name(5), "AREA06");
    // The per-player path fails the same way, by the same code.
    CHECK_INT(read_back.player_flags[1][4], 0);
    CHECK_INT(read_back.player_flags[1][5], 1);
    // And the world map's last destination now points at AREA06.
    CHECK_INT(read_back.last, 5);
}

// LIMITATION: reusing a released id for a different location hands that
// location the old one's discovery state. Contiguity is intact throughout,
// which is why an id policy cannot be replaced by a validator rule.
TEST(reusing_an_id_gives_the_replacement_the_old_state)
{
    static const int ids[] = { 0, 1, 2, 3, 4, 5, 6 };
    static const char* const replaced[] = {
        "AREA00", "AREA01", "AREA02", "AREA03", "AREA04", "AREA05", "OTHERPLACE"
    };
    AreaBlock written;
    AreaBlock read_back;

    CHECK(write_contiguous_areas(7));
    CHECK(reload_areas());
    CHECK_STR(area_get_name(6), "AREA06");

    block_init(&written, 7);
    written.flags[6] = 1;
    written.last = 6;
    CHECK(write_save_block(&written, true, false));

    // Mod A is uninstalled and mod B, which claims the same id, is installed.
    CHECK(write_area_fixture(ids, replaced, 7));
    CHECK(reload_areas());
    CHECK_STR(area_get_name(6), "OTHERPLACE");

    CHECK(load_save_block());
    CHECK(save_and_read_block(&read_back));

    // A location the player has never seen is on their world map, at the
    // coordinates of the new area.
    CHECK_INT(read_back.flags[6], 1);
    CHECK_INT(read_back.last, 6);
}

// The engine reads the list by rank, and mes.c sorts entries by id on load,
// so a gap makes rank and id different numbers from the gap upwards. This is
// the measurement behind the contiguity rule in mods/ID-BUDGETS.md.
TEST(a_gap_makes_rank_diverge_from_id)
{
    static const int gapped[] = { 0, 1, 2, 3, 4, 90 };
    AreaBlock written;
    AreaBlock read_back;

    CHECK(write_areas_named(gapped, 6));
    CHECK(reload_areas());

    // Six entries, so six areas - the id 90 is not a slot number.
    CHECK_INT(area_count(), 6);
    CHECK_STR(area_get_name(5), "AREA90");

    block_init(&written, 6);
    written.flags[5] = 1;
    written.last = 5;
    CHECK(write_save_block(&written, true, false));

    // Whoever takes id 5 later inherits the state authored id 90 wrote.
    CHECK(write_contiguous_areas(6));
    CHECK(reload_areas());
    CHECK(load_save_block());
    CHECK(save_and_read_block(&read_back));

    CHECK_INT(read_back.flags[5], 1);
    CHECK_STR(area_get_name(5), "AREA05");
}

// A list that does not start at zero does not miscount - it **crashes the
// module loader**, and this is the sharpest reason the toolkit refuses such a
// list before it reaches the game.
//
// `area_mod_load` seeds its walk with `mes_get_msg(0)`, which does not fail on
// a miss: `mes.c` hands back the string "Error! Missing line 0 in
// mes\\gamearea.mes" and lets the caller parse it as an area record. The first
// `tig_str_parse_value_64` finds no separator in it, so it sets the caller's
// cursor to NULL (str_parse.c:95, faithful to 0x531A20), and the second call
// dereferences that NULL. The original binary has the same shape, so this is
// an engine property, not a porting defect - see MODDING-NOTES.md quirk 39.
//
// Measured in a child process because the failure is a signal, not a return
// value. Not built on Windows, where there is no `fork`; the finding is about
// the engine and one platform is enough to hold it.
#ifndef _WIN32
TEST(a_list_that_does_not_start_at_zero_crashes_the_module_loader)
{
    static const int no_zero[] = { 1, 2, 3, 4, 5 };
    pid_t child;
    int status = 0;

    CHECK(write_areas_named(no_zero, 5));
    if (area_fixture_loaded) {
        area_mod_unload();
        area_fixture_loaded = false;
    }

    fflush(NULL);
    child = fork();
    if (child == 0) {
        // A hang would be a different failure and must not become a stuck
        // test run.
        alarm(10);
        area_mod_load();
        _exit(0);
    }

    CHECK(child > 0);
    if (child > 0) {
        CHECK(waitpid(child, &status, 0) == child);
        CHECK(WIFSIGNALED(status));
        CHECK_INT(WIFSIGNALED(status) ? WTERMSIG(status) : 0, SIGSEGV);
    }

    // Leave a well-formed list behind for whatever runs next.
    CHECK(write_contiguous_areas(6));
    CHECK(reload_areas());
}
#endif

// The other half of card H4: a save written before the count prefix existed.
// The count is recovered from the distance to gamelib's sentinel.
TEST(an_original_layout_save_recovers_its_count)
{
    AreaBlock written;
    AreaBlock read_back;

    CHECK(write_contiguous_areas(6));
    CHECK(reload_areas());

    // Seven areas were in force when this one was written, and there is no
    // prefix to say so.
    block_init(&written, 7);
    written.flags[2] = 1;
    written.flags[6] = 1;
    written.last = 2;
    CHECK(write_save_block(&written, false, true));

    CHECK(load_save_block());
    CHECK(save_and_read_block(&read_back));

    CHECK_INT(read_back.count, 6);
    // Read at the width the save was written at: rank 2 survives, and the
    // last-known value is the one that followed the seven-byte array rather
    // than a byte out of the middle of it.
    CHECK_INT(read_back.flags[2], 1);
    CHECK_INT(read_back.last, 2);
}

TEST(an_implausible_count_is_refused)
{
    FILE* stream;
    unsigned int magic = AREA_MAGIC;
    int count = 1 << 24;

    CHECK(write_contiguous_areas(6));
    CHECK(reload_areas());

    stream = fopen(SAVE_FIXTURE, "wb");
    CHECK(stream != NULL);
    if (stream != NULL) {
        fwrite(&magic, sizeof(magic), 1, stream);
        fwrite(&count, sizeof(count), 1, stream);
        fclose(stream);
    }

    // Refused, not used to size an allocation from a truncated file.
    CHECK(!load_save_block());
}

void test_area_suite(void)
{
    // The fixture lives beside the test binary and is found the way the game
    // finds `mes\\gamearea.mes`: through a directory repository. Adding "."
    // twice is harmless, and a test run adds no archives, so nothing else
    // becomes visible.
    tig_file_repository_add(".");

    RUN(round_trip_preserves_flags_and_last_known);
    RUN(appending_an_area_keeps_every_earlier_area);
    RUN(removing_the_top_area_leaves_last_known_out_of_range);
    RUN(removing_a_lower_area_moves_state_to_the_wrong_place);
    RUN(reusing_an_id_gives_the_replacement_the_old_state);
    RUN(a_gap_makes_rank_diverge_from_id);
#ifndef _WIN32
    RUN(a_list_that_does_not_start_at_zero_crashes_the_module_loader);
#endif
    RUN(an_original_layout_save_recovers_its_count);
    RUN(an_implausible_count_is_refused);

    if (area_fixture_loaded) {
        area_mod_unload();
        area_fixture_loaded = false;
    }
    remove(AREA_FIXTURE);
    remove(SAVE_FIXTURE);
    tig_file_rmdir(AREA_DIR);
}
