#ifndef ARCANUM_GAME_ARMOR_RULES_H_
#define ARCANUM_GAME_ARMOR_RULES_H_

#include <stdbool.h>
#include <stdint.h>

// CE (turn-based rebalance, armor milestone 2): the armor table,
// `rules/armor.mes`, read at combat init and answered only under
// `armor penetration`, default off.
//
// One entry per listed armor piece, keyed by prototype number, and five
// reserved entries for the default penetration of each kind of attack:
//
//     {8094}{Protection: 20}                    body armor, helmet, gloves or boots
//     {8201}{Protection: 25, BlockChance: 18}   a shield: block rating and chance
//     {1}{Penetration: 30}   melee weapons
//     {2}{Penetration: 30}   bows
//     {3}{Penetration: 20}   thrown weapons
//     {4}{Penetration: 15}   unarmed, and creatures' natural attacks
//     {5}{Penetration: 40}   firearms the weapon table gives none
//
// A weapon's own penetration is the weapon table's `Penetration` key
// (`weapon_rules.h`). The file is generated by arcanum-work
// `scripts/armor_table.py` from the Combat Rebalance's armor sheet; the rules
// that use it are `penetration.h`.

#define ARMOR_RULE_UNSET (-1)
#define ARMOR_RULE_VALUE_MAX 1000
#define ARMOR_RULE_CHANCE_MAX 100

typedef enum ArmorRuleKind {
    ARMOR_RULE_KIND_MELEE = 1,
    ARMOR_RULE_KIND_BOW = 2,
    ARMOR_RULE_KIND_THROWN = 3,
    ARMOR_RULE_KIND_NATURAL = 4,
    ARMOR_RULE_KIND_FIREARM = 5,
    ARMOR_RULE_KIND_COUNT,
} ArmorRuleKind;

typedef struct ArmorRule {
    // A prototype number, or an `ArmorRuleKind`.
    int id;
    int protection;
    int block_chance;
    int penetration;
} ArmorRule;

// Pure: reads one entry into `rule`. False, with `rule` untouched, for
// anything the engine would misread: an unknown key, a value that is not a
// number, a kind entry (1-5) without Penetration or with anything else, a
// piece without Protection or with Penetration, an id that is neither.
// Values are clamped to 0..1000, BlockChance to 0..100.
bool armor_rule_parse(int id, const char* str, ArmorRule* rule);

void armor_rules_init(void);
void armor_rules_exit(void);
void armor_rules_load(void);

// Under `armor penetration`. True, with `*protection` set, when the armor
// object's prototype is listed.
bool armor_rules_protection(int64_t armor_obj, int* protection);
// Under `armor penetration`. True, with `*chance` set, when the shield's
// prototype is listed with a BlockChance.
bool armor_rules_block_chance(int64_t shield_obj, int* chance);
// Under `armor penetration`. The default penetration of a kind of attack, or
// ARMOR_RULE_UNSET when the file does not give one.
int armor_rules_default_penetration(ArmorRuleKind kind);

#endif /* ARCANUM_GAME_ARMOR_RULES_H_ */
