#ifndef ARCANUM_GAME_CREATURE_RULES_H_
#define ARCANUM_GAME_CREATURE_RULES_H_

#include <stdbool.h>
#include <stdint.h>

// CE (turn-based rebalance, creature profiles, zsogg 2026-10-21): what kind of
// body a creature has, read at combat init from `rules/creatures.mes` and
// answered only under `creature profiles`, default off.
//
// Six profiles decide what a critical hit does to a creature:
//
//   living      everyone not below; the stock effects
//   skeletal    undead bone: only a crushing critical shatters a limb
//   fleshy      undead flesh: a limb loosens, the head staggers
//   mechanical  a machine: it malfunctions, an arm jams, a leg hobbles
//   spirit      no body to hurt: a critical disrupts it
//   phantom     armor animated by nothing: only a critical hit, magic or an
//               explosive hurts it, and a critical always finds the gap
//
// One entry per listed creature, keyed by prototype number (description + 20,
// as the weapon and armor tables); every key is optional, at least one given:
//
//     {28341}{Profile: skeletal, FirearmScale: 50}
//     {28330}{Profile: spirit, Natural: 55}
//     {28348}{Chart: snake}
//
// Profile    living, skeletal, fleshy, mechanical, spirit or phantom
// Chart      the body chart a critical reads in place of the creature's own:
//            biped, quadruped, amorphous, insect, snake or avian
// Natural    the natural protection weapon hits meet under `armor
//            penetration`, in place of the creature's normal resistance (and
//            the undead's share of it)
// FirearmScale  the share of a firearm hit's damage it takes, in percent
//
// A creature not listed takes the profile its flags give
// (`creature_profile_default`). The file is generated by arcanum-work
// `scripts/creature_table.py` from the Combat Rebalance's creature sheet; the
// design is arcanum-work `docs/CREATURE-PROFILES.md`.

#define CREATURE_RULE_UNSET (-1)
#define CREATURE_RULE_VALUE_MAX 1000
#define CREATURE_RULE_SCALE_MAX 100

typedef enum CreatureProfile {
    // `creature profiles` is off, or the object is no critter.
    CREATURE_PROFILE_NONE = -1,
    CREATURE_PROFILE_LIVING,
    CREATURE_PROFILE_SKELETAL,
    CREATURE_PROFILE_FLESHY,
    CREATURE_PROFILE_MECHANICAL,
    CREATURE_PROFILE_SPIRIT,
    CREATURE_PROFILE_PHANTOM,
    CREATURE_PROFILE_COUNT,
} CreatureProfile;

typedef struct CreatureRule {
    // A prototype number.
    int id;
    // A `CreatureProfile`, or CREATURE_RULE_UNSET.
    int profile;
    // A `CritBodyType`, or CREATURE_RULE_UNSET.
    int chart;
    int natural;
    int firearm_scale;
} CreatureRule;

// Pure: reads one entry into `rule`. False, with `rule` untouched, for an
// unknown key, a profile or chart that is none of the names above, a value
// that is not a number, an entry with no key, or an id of 0 or less. Natural
// is clamped to 0..1000, FirearmScale to 0..100.
bool creature_rule_parse(int id, const char* str, CreatureRule* rule);

// Pure: the profile of a creature not listed, from its critter flags
// (`OBJ_F_CRITTER_FLAGS`, `OBJ_F_CRITTER_FLAGS2`) and its body chart:
// mechanical; amorphous or elemental, spirit; undead, fleshy; else living.
CreatureProfile creature_profile_default(unsigned int critter_flags,
    unsigned int critter_flags2, int chart);
// Pure: whether a critical may stun, knock out, cripple, blind or scar it -
// living creatures only.
bool creature_profile_bodily(CreatureProfile profile);
// Pure: whether a critical may knock it down (a biped's chart still needed).
bool creature_profile_knockdown(CreatureProfile profile);
// Pure: the knockdown roll's extra points: a crushing critical on bone, 10.
int creature_profile_knockdown_bonus(CreatureProfile profile, int crit_hit_type);
// Pure: the temporary effects (`crit_effects.h`) a critical leaves, by where
// it struck and the weapon's `CritHitType`. Living creatures take the stock
// location's effect (`crit_effects_for_location`).
unsigned int creature_profile_temporary(CreatureProfile profile, int hit_loc,
    int crit_hit_type);
// Pure: the profile's name as the file spells it, or NULL.
const char* creature_profile_name(CreatureProfile profile);
// Pure: the line examining a creature of this profile shows in place of its
// reaction, or NULL: a phantom's says what hurts it (2026-10-22).
const char* creature_profile_examine_hint(CreatureProfile profile);

void creature_rules_init(void);
void creature_rules_exit(void);
void creature_rules_load(void);

// Under `creature profiles`: the critter's profile, its listed one or the
// default its flags give. CREATURE_PROFILE_NONE when off or not a critter.
CreatureProfile creature_rules_profile(int64_t obj);
// The body chart a critical reads: under `creature profiles` a listed Chart,
// else the critter's own `OBJ_F_CRITTER_CRIT_HIT_CHART`.
int creature_rules_body_chart(int64_t obj);
// Under `creature profiles`: true, with `*natural` set, when it is listed
// with a Natural.
bool creature_rules_natural(int64_t obj, int* natural);
// Under `creature profiles`: its FirearmScale, or 100.
int creature_rules_firearm_scale(int64_t obj);

#endif /* ARCANUM_GAME_CREATURE_RULES_H_ */
